// The logic of M2: creating a new Homebrew object as a linked pair, a Library entry and a world document, over Flight
// Control's document.create (contract, section 4, "Documents"; Apply of M2, decision 1-3). The Library is the source
// (N14 a), so it is written first; the world document is written only after the Library entry exists, so a failure
// never leaves a world document without one. Both share the given id (Apply decision 2, "same id"); each also carries
// a flag pointing at the other side, as a fallback for the rare case a later Foundry operation changes the id on one
// side only.

// A JSON-only copy of Flight Control's type (contract, section 1); not shared code (E7), see v13/flight-control-api.d.ts.
export type JsonValue = null | boolean | number | string | readonly JsonValue[] | { readonly [key: string]: JsonValue };

export type RequestOutcome = { readonly ok: true; readonly value: JsonValue } | { readonly ok: false; readonly reason: string; readonly detail: string };

// What this file needs from Flight Control: sending one request and getting its outcome. In Foundry this is
// `game.modules.get("eagle-flight-control")?.api.request(...)`; v13/create-pair.ts wires the real one.
export interface RequestSender {
  request(type: string, payload: JsonValue): Promise<RequestOutcome>;
}

// document.create only creates Actor, Item, JournalEntry or RollTable (Flight Control's CREATABLE_DOCUMENT_TYPES);
// Homebrew's 18 kinds need only the first three (N15: no Player Character, and Homebrew has no journal entries).
export type HomebrewWorldType = "Actor" | "Item" | "RollTable";

export interface CreatePairTarget {
  // The Library compendium this kind belongs to, e.g. "world.eagle-loot-2014" (`EagleLibrary/docs/library-convention.md`).
  readonly libraryPack: string;
  readonly worldType: HomebrewWorldType;
}

export type SideResult = { readonly created: boolean; readonly uuid: string } | { readonly failed: true; readonly reason: string; readonly detail: string };

export interface CreatePairResult {
  readonly id: string;
  readonly library: SideResult;
  // Undefined only when the Library side failed and the world side was therefore never asked.
  readonly world?: SideResult;
}

const sideOf = (outcome: RequestOutcome): SideResult => {
  if (!outcome.ok) return { failed: true, reason: outcome.reason, detail: outcome.detail };
  const value = outcome.value as { created?: unknown; uuid?: unknown };
  return { created: value.created === true, uuid: typeof value.uuid === "string" ? value.uuid : "" };
};

// Creates the pair: first the Library entry, with a flag naming the world side; then, only if that succeeded, the
// world document, with a flag naming the Library side. `id` is generated by the caller (`foundry.utils.randomID()` in
// v13/create-pair.ts), so a repeated call after a partial failure writes nothing twice (document.create is itself
// idempotent per id).
export async function createPair(
  sender: RequestSender,
  target: CreatePairTarget,
  id: string,
  data: Readonly<Record<string, JsonValue>>,
): Promise<CreatePairResult> {
  const libraryOutcome = await sender.request("document.create", {
    target: { pack: target.libraryPack },
    id,
    data: { ...data, flags: { "eagle-homebrew": { pair: { world: target.worldType } } } },
  });
  const library = sideOf(libraryOutcome);
  if ("failed" in library) return { id, library };

  const worldOutcome = await sender.request("document.create", {
    target: { world: target.worldType },
    id,
    data: { ...data, flags: { "eagle-homebrew": { pair: { pack: target.libraryPack } } } },
  });
  return { id, library, world: sideOf(worldOutcome) };
}
